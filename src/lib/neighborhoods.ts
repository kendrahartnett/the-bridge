export type CommunityArea = (typeof COMMUNITY_AREAS)[number]

const COMMON_NAMES: Partial<Record<CommunityArea, string>> = {
  "Lower West Side": "Pilsen",
  "South Lawndale": "Little Village",
  "Near South Side": "South Loop",
}

export function neighborhoodLabel(area: string): string {
  const common = COMMON_NAMES[area as CommunityArea]
  return common ? `${area} (${common})` : area
}
